#include <string>
#include <vector>

void count_vowels() {
    std::string text = "prism bridge";
    int vowels = 0;
    for (std::size_t i = 0; i < text.size(); ++i) {
        char ch = text[i];
        if (ch == 'a' || ch == 'e' || ch == 'i' || ch == 'o' || ch == 'u') vowels += 1;
    }
    (void)vowels;
}

void fibonacci_sum() {
    int f0 = 0, f1 = 1;
    int acc = 0;
    for (int i = 0; i < 10; ++i) {
        acc += f0;
        int next = f0 + f1;
        f0 = f1;
        f1 = next;
    }
    (void)acc;
}

void parity_count() {
    int evens = 0, odds = 0;
    for (int i = 1; i <= 20; ++i) {
        if (i % 2 == 0) evens += 1; else odds += 1;
    }
    (void)evens;
    (void)odds;
}

void sum_odds() {
    int acc = 0;
    for (int i = 1; i <= 10; ++i) {
        if (i % 2 != 0) acc += i;
    }
    (void)acc;
}

extern "C" int golden_hollow();
extern "C" void clever_bridge();
extern "C" void mellow_grove();
extern "C" void bright_thorn();

int main() {
    count_vowels();
    fibonacci_sum();
    parity_count();
    sum_odds();
    clever_bridge();
    mellow_grove();
    bright_thorn();
    return golden_hollow();
}
